"""Synchronous SQL Server storage for the LOCAL educational FastAPI service.

Only called by POST /predict AFTER input validation and successful inference.
A 200 response is returned only after the transaction commit has succeeded.
No training, table creation, source-data changes, background inserts, or retries.

The default connection reproduces the user's verified local Windows-auth setup.
TrustServerCertificate=yes is for this local demonstration only. For deployment,
use a validated TLS certificate, authentication, least-privilege database access,
and an externally supplied PIPE_SQL_CONNECTION_STRING; never commit passwords.
"""
from __future__ import annotations

import json
import logging
import os
from datetime import datetime, timezone
from typing import Any

import pyodbc

logger = logging.getLogger("pipe_api.storage")

LOCAL_CONNECTION_STRING = (
    r"DRIVER={ODBC Driver 17 for SQL Server};SERVER=Saba-PC\SQLEXPRESS;"
    r"DATABASE=OilGas_Pipeline_Prediction;Trusted_Connection=yes;"
    r"Encrypt=yes;TrustServerCertificate=yes;"
)
CONNECTION_TIMEOUT_SECONDS = 5
QUERY_TIMEOUT_SECONDS = 5

INSERT_SQL = """
INSERT INTO dbo.PredictionLogs
    (ModelId, PredictedCondition, InputJson, OutputJson)
OUTPUT INSERTED.PredictionId, INSERTED.CreatedAtUtc
VALUES (?, ?, ?, ?);
"""
# Complete the stored JSON receipt in the SAME transaction, before commit.
UPDATE_SQL = """
UPDATE dbo.PredictionLogs
SET OutputJson = ?
WHERE PredictionId = ?;
"""


class PredictionStoreError(RuntimeError):
    """The application did not receive confirmation of durable storage."""


def _encode_json(value: dict[str, Any]) -> str:
    return json.dumps(value, ensure_ascii=False, allow_nan=False, separators=(",", ":"))


def _close_safely(resource: Any) -> None:
    if resource is not None:
        try:
            resource.close()
        except Exception as exc:
            # Avoid disclosing connection strings, input rows, or credentials.
            logger.warning("Database cleanup failed (%s).", type(exc).__name__)


def save_prediction(
    input_data: dict[str, Any], prediction: dict[str, Any]
) -> dict[str, Any]:
    """Commit one log row; return its ID/time with the original model response.

    Each accepted POST is a new log entry, even when its input is identical.
    Do not automatically retry writes after a timeout: commit acknowledgement can
    be lost even when the server has committed. Check the table before retrying.
    The new fields are a storage receipt, not evidence of model correctness.
    """
    connection = None
    cursor = None
    try:
        model_id = prediction.get("model_id")
        condition = prediction.get("predicted_condition")
        if not isinstance(model_id, str) or not 1 <= len(model_id) <= 100:
            raise ValueError("Model ID is missing or exceeds the log schema.")
        if condition not in ("Critical", "Moderate", "Normal"):
            raise ValueError("Unexpected prediction class.")
        input_json = _encode_json(input_data)
        output_json = _encode_json(prediction)
        connection_string = os.environ.get("PIPE_SQL_CONNECTION_STRING", LOCAL_CONNECTION_STRING)
        if not connection_string.strip():
            raise ValueError("Database connection configuration is empty.")
        connection = pyodbc.connect(
            connection_string, timeout=CONNECTION_TIMEOUT_SECONDS, autocommit=False
        )
        connection.timeout = QUERY_TIMEOUT_SECONDS
        cursor = connection.cursor()
        row = cursor.execute(
            INSERT_SQL, model_id, condition, input_json, output_json
        ).fetchone()
        if row is None or int(row[0]) <= 0 or not isinstance(row[1], datetime):
            raise RuntimeError("The database did not return a valid log receipt.")
        # CreatedAtUtc is generated by SQL Server's SYSUTCDATETIME default.
        created_at = row[1]
        if created_at.tzinfo is None:
            created_at = created_at.replace(tzinfo=timezone.utc)
        else:
            created_at = created_at.astimezone(timezone.utc)
        saved_result = dict(prediction)
        saved_result.update({
            "prediction_id": int(row[0]),
            "saved_at_utc": created_at.isoformat(timespec="milliseconds").replace("+00:00", "Z"),
            "database_saved": True,
        })
        cursor.execute(UPDATE_SQL, _encode_json(saved_result), int(row[0]))
        # Rowcount can be -1 with driver/NOCOUNT settings. Positive mismatches
        # indicate an unexpected table behavior and must not report success.
        if cursor.rowcount not in (1, -1):
            raise RuntimeError("Could not finalize the inserted log receipt.")
        connection.commit()
        # Nothing leaves this function as a success before commit returns.
        logger.info("Prediction stored: id=%s model=%s", row[0], model_id)
        return saved_result
    except Exception as exc:
        if connection is not None:
            try:
                connection.rollback()
            except Exception as rollback_error:
                logger.warning("Database rollback unconfirmed (%s).", type(rollback_error).__name__)
        # Report only a standard SQLSTATE, never arbitrary ODBC error text.
        sqlstate = "unavailable"
        if isinstance(exc, pyodbc.Error) and exc.args:
            candidate = exc.args[0]
            if isinstance(candidate, str) and len(candidate) == 5 and candidate.isalnum():
                sqlstate = candidate
        logger.error(
            "Prediction storage not confirmed (%s; SQLSTATE=%s). "
            "Check SQL Server/table permissions and the last saved row before retrying.",
            type(exc).__name__, sqlstate,
        )
        raise PredictionStoreError("SQL Server did not confirm prediction storage.") from exc
    finally:
        _close_safely(cursor)
        _close_safely(connection)
